/** The i18n key naming a provider sign-in failure the server sent back as
 *  `oauth_error=<reason>` (a closed vocabulary — see ayane's `OAuthError`).
 *  An unknown reason reads as the generic failure. */
export function oauthErrorKey(reason: string): string {
  switch (reason) {
    case "denied":
    case "state":
    case "binding":
    case "unlinked":
    case "unreachable":
    case "already_linked":
    case "unconfigured":
      return `login.error.${reason}`;
    case "unknown_provider":
    case "not_configured":
      return "login.error.unconfigured";
    default:
      return "login.error.generic";
  }
}
